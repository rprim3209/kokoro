function translateString(src) {
  if (src == null) return src;
  var text = String(src);
  var lead = (text.match(/^\s*/) || [""])[0];
  var trail = (text.match(/\s*$/) || [""])[0];
  var core = text.trim();
  if (!core) return text;
  if (I18N_EN[core]) return lead + I18N_EN[core] + trail;
  var bare = core.replace(/:\s*$/, "");
  if (bare !== core && I18N_EN[bare]) {
    return lead + I18N_EN[bare] + core.slice(bare.length) + trail;
  }
  // Pattern labels with numbers, then longer phrase map.
  var out = text
    .replace(/Offline-Katalog\s*\((\d+)\)/g, "Offline catalog ($1)")
    .replace(/Katalog geladen · Live-Suche ggf\. eingeschränkt\s*\((\d+)\)/g, "Catalog loaded · live search may be limited ($1)")
    .replace(/Live-Katalog\s*\((\d+)\s*Produkte\)/g, "Live catalog ($1 products)")
    .replace(/Offline-Fallback\s*\((\d+)\s*Produkte\)/g, "Offline fallback ($1 products)")
    .replace(/\bNacht\s+(\d+)\s+·\s+Tag\s+(\d+)\s+\(Heuristik\)/g, "Night $1 · Day $2 (heuristic)")
    .replace(/Routine-Abdeckung:\s*(\d+)\s+von\s+(\d+)\s+Schritten belegt/g, "Routine coverage: $1 of $2 steps filled")
    .replace(/(\d+)\s+Flaschen\b/g, "$1 bottles")
    .replace(/\b1\s+Flasche\b/g, "1 bottle")
    .replace(/(\d+)\s+Produkte\b/g, "$1 products")
    .replace(/\b1\s+Produkt\b/g, "1 product");
  // Extra chrome patterns (dynamic counts / prefixes)
  out = out
    .replace(/Alle\s+(\d+)\s+Lücken füllen/g, "Fill all $1 gaps")
    .replace(/Alle Lücken füllen\s*\((\d+)\)/g, "Fill all gaps ($1)")
    .replace(/⚡\s*Alle\s+(\d+)\s+Lücken füllen/g, "⚡ Fill all $1 gaps");
  var keys = i18nKeys();
  for (var i = 0; i < keys.length; i++) {
    var key = keys[i];
    // Exact full-string match already handled above. For in-string replace:
    // allow long phrases, or short chrome labels (end with : / ·, or multi-word ≥4).
    if (key.length < 4) continue;
    if (key.length < 10) {
      var shortOk = /[:·]\s*$/.test(key) || /\s/.test(key);
      if (!shortOk) continue;
    }
    if (out.indexOf(key) === -1) continue;
    out = out.split(key).join(I18N_EN[key]);
  }
  return out;
}

