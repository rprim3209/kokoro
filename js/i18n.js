function currentLang() {
  try {
    return localStorage.getItem("kokoro-lang") === "en" ? "en" : "de";
  } catch (e) {
    return "de";
  }
}

var i18nPhraseKeys = null;
function i18nKeys() {
  if (!i18nPhraseKeys) {
    i18nPhraseKeys = Object.keys(I18N_EN).sort(function (a, b) { return b.length - a.length; });
  }
  return i18nPhraseKeys;
}

function translateString(src) {
  if (src == null) return src;
  var text = String(src);
  var lead = (text.match(/^\s*/) || [""])[0];
  var trail = (text.match(/\s*$/) || [""])[0];
  var core = text.trim();
  if (!core) return text;
  if (I18N_EN[core]) return lead + I18N_EN[core] + trail;
  var bare = core.replace(/:\s*$/, "");
  if (bare !== core && I18N_EN[bare]) {
    return lead + I18N_EN[bare] + core.slice(bare.length) + trail;
  }
  var out = text;
  var keys = i18nKeys();
  for (var i = 0; i < keys.length; i++) {
    var key = keys[i];
    if (key.length < 10) continue;
    if (out.indexOf(key) === -1) continue;
    out = out.split(key).join(I18N_EN[key]);
  }
  return out;
}

var i18nOriginalText = new WeakMap();

function applyI18n(root) {
  if (!root) return;
  var en = currentLang() === "en";
  var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
  var nodes = [];
  var node;
  while ((node = walker.nextNode())) nodes.push(node);
  nodes.forEach(function (textNode) {
    var parent = textNode.parentElement;
    if (!parent) return;
    if (parent.closest && parent.closest("[data-i18n-skip]")) return;
    var tag = parent.tagName;
    if (tag === "SCRIPT" || tag === "STYLE") return;
    if (!i18nOriginalText.has(textNode)) i18nOriginalText.set(textNode, textNode.nodeValue);
    var src = i18nOriginalText.get(textNode);
    textNode.nodeValue = en ? translateString(src) : src;
  });
  root.querySelectorAll("[placeholder], [title], [aria-label]").forEach(function (el) {
    if (el.closest && el.closest("[data-i18n-skip]")) return;
    ["placeholder", "title", "aria-label"].forEach(function (attr) {
      if (!el.hasAttribute(attr)) return;
      var store = "i18n" + attr;
      if (!el.dataset[store]) el.dataset[store] = el.getAttribute(attr);
      var src = el.dataset[store];
      el.setAttribute(attr, en ? translateString(src) : src);
    });
  });
  if (en) document.title = "Cosmetic Cabinet — evidence-based routine guide";
  else document.title = "Kosmetikschrank — Evidenzbasierter Routine- & Schrank-Wächter";
  document.documentElement.lang = en ? "en" : "de";
  updateLangButton();
}

function updateLangButton() {
  var btn = document.getElementById("langToggle");
  if (!btn) return;
  var on = currentLang() === "en";
  btn.classList.toggle("is-on", on);
  btn.setAttribute("aria-pressed", on ? "true" : "false");
  btn.setAttribute("aria-label", on ? "English on. Tap to switch back to German." : "English off. Tap to switch the app to English.");
}

function toggleAppLanguage() {
  var next = currentLang() === "en" ? "de" : "en";
  var view = (typeof appState !== "undefined" && appState && appState.view) || "cabinet";
  var profileId = (typeof appState !== "undefined" && appState) ? appState.activeProfileId : "";
  if (typeof syncActiveProfileFromWorkingState === "function") syncActiveProfileFromWorkingState();
  if (typeof saveState === "function") saveState();
  try { localStorage.setItem("kokoro-lang", next); } catch (e) { /* private mode */ }
  if (profileId && appState && Array.isArray(appState.profiles) && typeof loadProfileToAppState === "function") {
    var same = null;
    for (var i = 0; i < appState.profiles.length; i++) {
      if (appState.profiles[i] && appState.profiles[i].id === profileId) same = appState.profiles[i];
    }
    if (same) loadProfileToAppState(same);
  }
  if (typeof appState !== "undefined" && appState) appState.view = view;
  if (typeof updateCategoryNav === "function") updateCategoryNav();
  if (typeof updateBottomNav === "function") updateBottomNav();
  if (typeof renderCurrentScreen === "function") renderCurrentScreen();
  else applyI18n(document.body);
}

